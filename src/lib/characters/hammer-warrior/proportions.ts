export function heightScale(height: number) {
  if (!Number.isFinite(height)) throw new Error('Character height must be finite.');
  return Math.min(HEIGHT_RANGE.max, Math.max(HEIGHT_RANGE.min, height)) / DEFAULT_HEIGHT;
}
